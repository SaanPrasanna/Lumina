//! Launchers for command-line tools that need Lumina's PHP, and the shims in
//! `bin/.shims` that put the active versions on the user's PATH.

use std::path::{Path, PathBuf};

use lumina_core::{Error, Result};
use lumina_shim::Target;
use serde::Serialize;

/// One command in the shim folder.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, specta::Type)]
#[serde(rename_all = "camelCase")]
pub struct Shim {
    /// `php`, `composer`, `node`, ...
    pub name: String,
    pub program: PathBuf,
    pub args: Vec<String>,
    /// e.g. "PHP 8.4.26".
    pub describes: String,
}

/// Commands the shim folder may contain.
pub const SHIM_NAMES: [&str; 7] = ["php", "composer", "node", "npm", "npx", "python", "mysql"];

/// Makes `dir` hold exactly `shims`: on Windows a copy of `shim_exe` per
/// command plus its `.shim` file (or a `.cmd` launcher when the shim
/// executable is not available), elsewhere an `exec` shell script. Commands
/// Lumina does not provide right now are removed, so the system's own (if
/// any) is found instead.
pub fn write_shims(dir: &Path, shim_exe: Option<&Path>, shims: &[Shim]) -> Result<()> {
    let io = |path: &Path| {
        let path = path.to_path_buf();
        move |source| Error::Io { path, source }
    };
    std::fs::create_dir_all(dir).map_err(io(dir))?;
    remove_replaced(dir);
    for shim in shims {
        let target = Target {
            program: shim.program.clone(),
            args: shim.args.clone(),
        };
        let comment = format!(
            "Generated by Lumina: {}. Rewritten when the version changes.",
            shim.describes
        );
        if cfg!(windows) {
            let shim_file = dir.join(format!("{}.shim", shim.name));
            write_if_changed(
                &shim_file,
                lumina_shim::render(&comment, &target).as_bytes(),
            )?;
            let exe = dir.join(format!("{}.exe", shim.name));
            let cmd = dir.join(format!("{}.cmd", shim.name));
            match shim_exe.filter(|p| p.is_file()) {
                Some(source) => {
                    if !same_file_content(source, &exe)
                        && let Err(err) = replace_exe(source, &exe)
                    {
                        tracing::warn!("could not update {}: {err}", exe.display());
                    }
                    let _ = std::fs::remove_file(&cmd);
                }
                None => {
                    let mut line = format!("@\"{}\"", shim.program.display());
                    for arg in &shim.args {
                        line.push_str(&format!(" \"{arg}\""));
                    }
                    let text = format!("@echo off\r\nrem {comment}\r\n{line} %*\r\n");
                    write_if_changed(&cmd, text.as_bytes())?;
                }
            }
        } else {
            let quote = |s: &str| format!("'{}'", s.replace('\'', r"'\''"));
            let mut line = format!("exec {}", quote(&shim.program.to_string_lossy()));
            for arg in &shim.args {
                line.push(' ');
                line.push_str(&quote(arg));
            }
            let path = dir.join(&shim.name);
            write_if_changed(
                &path,
                format!("#!/bin/sh\n# {comment}\n{line} \"$@\"\n").as_bytes(),
            )?;
            #[cfg(unix)]
            {
                use std::os::unix::fs::PermissionsExt;
                let _ = std::fs::set_permissions(&path, std::fs::Permissions::from_mode(0o755));
            }
        }
    }
    // Remove what is no longer provided.
    for name in SHIM_NAMES {
        if shims.iter().any(|s| s.name == name) {
            continue;
        }
        for file in [
            format!("{name}.exe"),
            format!("{name}.shim"),
            format!("{name}.cmd"),
            name.to_owned(),
        ] {
            let _ = std::fs::remove_file(dir.join(file));
        }
    }
    Ok(())
}

/// Copies `source` over `exe`. A shim that is running (`node` under Vite,
/// `php artisan serve`) cannot be overwritten on Windows but can be renamed:
/// it moves aside to `<name>.exe.<n>.old`, keeps running, and the new copy
/// takes its place. [`remove_replaced`] deletes the old one once it is free.
fn replace_exe(source: &Path, exe: &Path) -> std::io::Result<()> {
    let Err(err) = std::fs::copy(source, exe) else {
        return Ok(());
    };
    let aside = (0..100)
        .map(|n| exe.with_extension(format!("exe.{n}.old")))
        .find(|p| !p.exists())
        .ok_or(err)?;
    std::fs::rename(exe, &aside)?;
    std::fs::copy(source, exe).map(|_| ())
}

/// Deletes shims [`replace_exe`] moved aside; one still running stays.
fn remove_replaced(dir: &Path) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        if entry.file_name().to_string_lossy().ends_with(".old") {
            let _ = std::fs::remove_file(entry.path());
        }
    }
}

fn write_if_changed(path: &Path, bytes: &[u8]) -> Result<()> {
    if std::fs::read(path).is_ok_and(|old| old == bytes) {
        return Ok(());
    }
    std::fs::write(path, bytes).map_err(|source| Error::Io {
        path: path.to_path_buf(),
        source,
    })
}

fn same_file_content(a: &Path, b: &Path) -> bool {
    match (std::fs::metadata(a), std::fs::metadata(b)) {
        (Ok(ma), Ok(mb)) if ma.len() == mb.len() => std::fs::read(a).ok() == std::fs::read(b).ok(),
        _ => false,
    }
}

/// Writes `composer.bat` (Windows) and `composer` (shell) next to
/// `composer.phar` in `dir`, running it with `php` and `ini`.
pub fn write_composer_shims(dir: &Path, php: &Path, ini: &Path, php_version: &str) -> Result<()> {
    let phar = dir.join("composer.phar");
    if !phar.is_file() {
        return Ok(());
    }
    let io = |path: &Path| {
        let path = path.to_path_buf();
        move |source| Error::Io { path, source }
    };
    let bat = dir.join("composer.bat");
    let bat_text = format!(
        "@echo off\r\nrem Generated by Lumina: Composer with PHP {php_version}. Rewritten when the PHP version changes.\r\n\"{}\" -c \"{}\" \"%~dp0composer.phar\" %*\r\n",
        php.display(),
        ini.display()
    );
    std::fs::write(&bat, bat_text).map_err(io(&bat))?;

    let sh = dir.join("composer");
    let quote = |p: &Path| format!("'{}'", p.to_string_lossy().replace('\'', r"'\''"));
    let sh_text = format!(
        "#!/bin/sh\n# Generated by Lumina: Composer with PHP {php_version}. Rewritten when the PHP version changes.\nexec {} -c {} \"$(dirname \"$0\")/composer.phar\" \"$@\"\n",
        quote(php),
        quote(ini)
    );
    std::fs::write(&sh, sh_text).map_err(io(&sh))?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let _ = std::fs::set_permissions(&sh, std::fs::Permissions::from_mode(0o755));
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn shim(name: &str, program: &Path, args: &[&str]) -> Shim {
        Shim {
            name: name.into(),
            program: program.to_path_buf(),
            args: args.iter().map(|a| (*a).to_owned()).collect(),
            describes: format!("{name} test"),
        }
    }

    #[test]
    fn shims_are_written_updated_and_pruned() {
        let tmp = tempfile::tempdir().expect("tempdir");
        let dir = tmp.path().join(".shims");
        let php = tmp.path().join("php.exe");
        let fake_shim_exe = tmp.path().join("lumina-shim.exe");
        std::fs::write(&fake_shim_exe, b"shim binary").expect("exe");

        write_shims(
            &dir,
            Some(&fake_shim_exe),
            &[
                shim("php", &php, &["-c", "php.ini"]),
                shim("node", &php, &[]),
            ],
        )
        .expect("write");
        if cfg!(windows) {
            assert_eq!(
                std::fs::read(dir.join("php.exe")).expect("exe"),
                b"shim binary"
            );
            let target =
                lumina_shim::parse(&std::fs::read_to_string(dir.join("php.shim")).expect("shim"))
                    .expect("parse");
            assert_eq!(target.program, php);
            assert_eq!(target.args, ["-c", "php.ini"]);
        } else {
            let script = std::fs::read_to_string(dir.join("php")).expect("script");
            assert!(
                script.contains("exec ") && script.contains("'-c' 'php.ini' \"$@\""),
                "{script}"
            );
        }

        // node is no longer provided → its shim goes away; php stays.
        write_shims(&dir, Some(&fake_shim_exe), &[shim("php", &php, &[])]).expect("rewrite");
        let names: Vec<String> = std::fs::read_dir(&dir)
            .expect("dir")
            .flatten()
            .map(|e| e.file_name().to_string_lossy().into_owned())
            .collect();
        assert!(names.iter().all(|n| !n.starts_with("node")), "{names:?}");
        assert!(names.iter().any(|n| n.starts_with("php")));
    }

    /// Windows: a shim that is running is moved aside and replaced.
    #[cfg(windows)]
    #[test]
    fn a_running_shim_is_replaced() {
        let tmp = tempfile::tempdir().expect("tempdir");
        let exe = tmp.path().join("node.exe");
        let system = std::path::PathBuf::from(std::env::var_os("SystemRoot").expect("SystemRoot"));
        std::fs::copy(system.join("System32").join("PING.EXE"), &exe).expect("copy");
        let mut running = std::process::Command::new(&exe)
            .args(["-n", "30", "127.0.0.1"])
            .stdout(std::process::Stdio::null())
            .spawn()
            .expect("spawn");
        let source = tmp.path().join("lumina-shim.exe");
        std::fs::write(&source, b"new shim").expect("source");

        assert!(
            std::fs::copy(&source, &exe).is_err(),
            "a running exe cannot be overwritten"
        );
        replace_exe(&source, &exe).expect("replace");
        assert_eq!(std::fs::read(&exe).expect("read"), b"new shim");
        let aside = tmp.path().join("node.exe.0.old");
        assert!(aside.is_file());

        remove_replaced(tmp.path());
        assert!(aside.is_file(), "still running");
        running.kill().expect("kill");
        running.wait().expect("wait");
        remove_replaced(tmp.path());
        assert!(!aside.exists());
    }

    #[cfg(windows)]
    #[test]
    fn without_the_shim_binary_cmd_launchers_are_written() {
        let tmp = tempfile::tempdir().expect("tempdir");
        let dir = tmp.path().join(".shims");
        write_shims(
            &dir,
            None,
            &[shim(
                "php",
                Path::new(r"C:\php\php.exe"),
                &["-c", r"C:\php.ini"],
            )],
        )
        .expect("write");
        let cmd = std::fs::read_to_string(dir.join("php.cmd")).expect("cmd");
        assert!(
            cmd.contains(r#"@"C:\php\php.exe" "-c" "C:\php.ini" %*"#),
            "{cmd}"
        );
    }

    #[test]
    fn shims_point_at_the_given_php() {
        let tmp = tempfile::tempdir().expect("tempdir");
        write_composer_shims(tmp.path(), Path::new("php"), Path::new("php.ini"), "8.4.26")
            .expect("no phar: no-op");
        assert!(!tmp.path().join("composer.bat").exists());

        std::fs::write(tmp.path().join("composer.phar"), "<?php").expect("phar");
        let php = Path::new(r"C:\Lumina\bin\php\8.4.26\php.exe");
        write_composer_shims(
            tmp.path(),
            php,
            Path::new(r"C:\Lumina\etc\php\8.4.26\php.ini"),
            "8.4.26",
        )
        .expect("write");
        let bat = std::fs::read_to_string(tmp.path().join("composer.bat")).expect("bat");
        assert!(bat.contains(r#""C:\Lumina\bin\php\8.4.26\php.exe" -c "C:\Lumina\etc\php\8.4.26\php.ini" "%~dp0composer.phar" %*"#), "{bat}");
        let sh = std::fs::read_to_string(tmp.path().join("composer")).expect("sh");
        assert!(
            sh.starts_with("#!/bin/sh\n") && sh.contains("composer.phar\" \"$@\""),
            "{sh}"
        );
    }
}
